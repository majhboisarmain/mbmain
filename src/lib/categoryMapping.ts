/**
 * Returns list of matching category/subcategory terms for search query expansion.
 * E.g., searching "construction" returns JCB Rentals, Crane Rentals, Cement Dealers, Concrete, etc.
 */
export function expandCategorySearchTerms(query: string): string[] {
  if (!query || !query.trim()) return [];
  const q = query.trim().toLowerCase();
  const terms = new Set<string>();

  // Check synonym matches
  for (const syn in COMMON_SYNONYMS) {
    if (syn.startsWith(q) || q.startsWith(syn) || levenshteinDistance(q, syn) <= 2) {
      COMMON_SYNONYMS[syn].forEach(t => terms.add(t));
    }
  }

  CATEGORY_CATALOG.forEach(item => {
    const parentLower = item.parent.toLowerCase();
    const catLower = item.category.toLowerCase();

    // If query matches parent (e.g. "construction")
    if (parentLower.includes(q) || q.includes(parentLower)) {
      terms.add(item.category);
      terms.add(item.parent);
    }
    // If query matches category (e.g. "jcb")
    else if (catLower.includes(q)) {
      terms.add(item.category);
      terms.add(item.parent);
    }
  });

  return Array.from(terms);
}

/**
 * Get category suggestions for search bar autocomplete.
 * Strictly prioritizes word prefixes so searching "ash" returns "Ashrams", NOT "Car Wash" or "Fashion".
 */
export function getCategorySearchSuggestions(query: string, limit = 8): { title: string; parent: string; slug: string }[] {
  if (!query || !query.trim()) return [];
  const q = query.trim().toLowerCase();
  const results: { title: string; parent: string; slug: string }[] = [];
  const added = new Set<string>();

  const helperAdd = (title: string, parent: string, slug: string) => {
    if (!added.has(title)) {
      added.add(title);
      results.push({ title, parent, slug });
    }
  };

  // 1. Synonym & Misspelling Exact / Prefix Matches (e.g. "dr" -> "Doctors", "doctr" -> "Doctors")
  for (const syn in COMMON_SYNONYMS) {
    if (syn.startsWith(q) || (q.length >= 3 && syn === q)) {
      COMMON_SYNONYMS[syn].forEach(targetCat => {
        const catItem = CATEGORY_CATALOG.find(c => c.category.toLowerCase() === targetCat.toLowerCase());
        if (catItem) {
          helperAdd(catItem.category, catItem.parent, catItem.slug);
        } else {
          helperAdd(targetCat, "Services", targetCat.toLowerCase().replace(/\s+/g, '-'));
        }
      });
    }
  }

  // 2. Category Title Starts With Query (Highest Priority, e.g. "ash" -> "Ashrams")
  for (const item of CATEGORY_CATALOG) {
    if (results.length >= limit) break;
    const catLower = item.category.toLowerCase();
    if (catLower.startsWith(q)) {
      helperAdd(item.category, item.parent, item.slug);
    }
  }

  // 3. Any Word inside Category Title Starts With Query (e.g. "doc" -> "Pet Doctors")
  for (const item of CATEGORY_CATALOG) {
    if (results.length >= limit) break;
    const catLower = item.category.toLowerCase();
    const words = catLower.split(/[\s/&,-]+/);
    if (words.some(w => w.startsWith(q))) {
      helperAdd(item.category, item.parent, item.slug);
    }
  }

  // 4. Any Word inside Parent Category Starts With Query
  for (const item of CATEGORY_CATALOG) {
    if (results.length >= limit) break;
    const parentLower = item.parent.toLowerCase();
    const parentWords = parentLower.split(/[\s/&,-]+/);
    if (parentWords.some(w => w.startsWith(q))) {
      helperAdd(item.category, item.parent, item.slug);
    }
  }

  // 5. Typo Tolerance for 4+ character queries (e.g., "dokt" -> "Doctors")
  if (results.length < limit && q.length >= 4) {
    for (const item of CATEGORY_CATALOG) {
      if (results.length >= limit) break;
      if (!added.has(item.category)) {
        const words = item.category.toLowerCase().split(/[\s/&,-]+/);
        const hasFuzzyMatch = words.some(w => w.length >= 4 && levenshteinDistance(q, w.slice(0, q.length)) <= 1);
        if (hasFuzzyMatch) {
          helperAdd(item.category, item.parent, item.slug);
        }
      }
    }
  }

  return results.slice(0, limit);
}
